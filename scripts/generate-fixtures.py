"""Generate original compatibility fixtures using the installed Grace binary."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures"


def run(args, commands, output):
    command = ["gracebat", "-noprint", "-noask", *args]
    for statement in commands:
        command.extend(["-pexec", statement])
    command.extend(["-saveall", str(FIXTURES / output)])
    result = subprocess.run(command, capture_output=True, text=True, check=True, timeout=30)
    if result.stderr.strip():
        raise RuntimeError(result.stderr)
    print(output)


run(
    ["-settype", "xy", str(FIXTURES / "reference.xy"), "-settype", "xydy", str(FIXTURES / "reference.xydy")],
    [
        "world 0, 0, 4, 1.2", 'title "Grace reference"',
        'subtitle "Generated by gracebat"', 'xaxis label "Time (s)"',
        'yaxis label "Amplitude"', "xaxis tick major 1", "yaxis tick major 0.2",
        's0 legend "Model"', "s0 line color 4", "s0 line linewidth 1.5",
        's1 legend "Measured"', "s1 line type 0", "s1 symbol 1",
        "s1 symbol color 2", "s1 errorbar color 2",
        'map color 16 to (25, 85, 65), "custom"', "legend 0.8, 0.75",
    ],
    "grace-reference.agr",
)
run(
    [str(FIXTURES / "grace-reference.agr"), "-graph", "2", "-settype", "xy", str(FIXTURES / "reference.xy")],
    [
        "with g2", "world 0.1, 0.05, 10, 2", "view 0.7, 0.2, 1.1, 0.5",
        "xaxes scale logarithmic", "xaxis tick major 10", 'title "Inset"',
        "with string", "string on", "string loctype view", "string 0.2, 0.9",
        'string def "Preserved annotation"',
    ],
    "grace-multigraph.agr",
)
