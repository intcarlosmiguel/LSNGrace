import { figureStyle, figureComments } from '../style/figure';
import { latexToGrace, graphLatex, asciiJson } from '../text/latex';
import { immutableRows } from '../scene/immutableRows';
const rowBlocks = new WeakMap<number[][], string>();
function rowBlock(rows: number[][]): string {
  const cacheable = immutableRows(rows);
  const cached = cacheable ? rowBlocks.get(rows) : undefined;
  if (cached !== undefined) return cached;
  const block = rows.map((row) => row.join(' ')).join('\n');
  if (cacheable) rowBlocks.set(rows, block);
  return block;
}
import type { Scene } from '../scene/types';
import { graphFields, pageFields, setFields, writeFields, quoted } from './fields';
import { validateScene } from '../scene/validate';
export function serializeAgr(scene: Scene, parametersOnly = false): string {
  if (scene.annotations.length || scene.graphs.some((g) => g.annotations.length))
    throw Error(
      'Anotações estruturadas ainda não são exportadas; mantenha-as como diretivas preservadas neste marco.',
    );
  const errors = [
    ...validateScene(scene),
    ...scene.compatibility.diagnostics
      .filter((d) => d.severity === 'error')
      .map((d) => `Linha ${d.line}: ${d.message}`),
  ];
  if (errors.length)
    throw Error(`Exportação interrompida para evitar perda de dados:\n${errors.join('\n')}`);
  const out = [
    '# Grace project file',
    '# Generated by LSNGrace',
    '@version 50122',
    ...writeFields(scene, pageFields),
  ];
  for (const f of scene.fonts)
    out.push(`@map font ${f.id} to ${quoted.write(f.name)}, ${quoted.write(f.fallback)}`);
  for (const c of scene.colors)
    out.push(`@map color ${c.id} to (${c.rgb.join(', ')}), ${quoted.write(c.name)}`);
  out.push(...scene.compatibility.preserved.filter((d) => d.scope === 'page').map((d) => d.raw));
  for (const g of scene.graphs) {
    if (!parametersOnly)
      for (const report of g.regressions ?? [])
        out.push(`# LSNGrace regression G${g.id} ${asciiJson(report)}`);
    out.push(
      `@g${g.id} ${g.enabled ? 'on' : 'off'}`,
      `@g${g.id} hidden ${g.hidden}`,
      `@g${g.id} type ${g.type}`,
      `@with g${g.id}`,
    );
    out.push(
      ...scene.compatibility.preserved
        .filter((d) => d.scope === 'graph' && d.graphId === g.id)
        .map((d) => d.raw),
    );
    const native = {
      ...g,
      title: { ...g.title, text: latexToGrace(g.title.text) },
      subtitle: { ...g.subtitle, text: latexToGrace(g.subtitle.text) },
      axes: Object.fromEntries(
        Object.entries(g.axes).map(([id, a]) => [
          id,
          { ...a, label: { ...a.label, text: latexToGrace(a.label.text) } },
        ]),
      ),
    };
    out.push(...writeFields(native, graphFields));
    for (const [id, axis] of Object.entries(g.axes))
      out.push(`@    ${id} tick ${axis.ticks.direction}`);
    out.push(`@    legend ${g.legend.position.join(', ')}`);
    for (const s of g.sets) {
      if (!parametersOnly && s.worksheet)
        out.push(`# LSNGrace worksheet G${g.id}.S${s.id} ${asciiJson(s.worksheet)}`);
      out.push(...writeFields({ ...s, legend: latexToGrace(s.legend) }, setFields, `s${s.id} `));
      if ((s.opacity ?? 1) !== 1 || (s.symbol.fill.opacity ?? 1) !== 1)
        out.push(
          `# LSNGrace alpha G${g.id}.S${s.id} ${s.opacity ?? 1} ${s.symbol.fill.opacity ?? 1}`,
        );
    }
  }
  out.push(
    figureComments(
      new Map(
        scene.graphs.flatMap((g) => {
          const style = figureStyle(g);
          return style ? [[g.id, style] as const] : [];
        }),
      ),
    ),
  );
  for (const g of scene.graphs)
    for (const [key, text] of graphLatex(g)) out.push(`# LSNGrace latex ${key} ${asciiJson(text)}`);
  if (!parametersOnly)
    for (const g of scene.graphs)
      for (const s of g.sets)
        if (s.rows.length) {
          out.push(`@target G${g.id}.S${s.id}`, `@type ${s.type}`);
          // Do not spread rows into function arguments: large scientific Sets
          // exceed the JavaScript engine's argument limit.
          out.push(rowBlock(s.rows));
          out.push('&');
        }
  return out.join('\n') + '\n';
}
